# Day 09 - Shorthand Operators

# -----------------------------------
# += Operator
# -----------------------------------

number = 10                      # Store value

number += 5                      # Add and assign

print(number)


# -----------------------------------
# -= Operator
# -----------------------------------

number = 20                      # Store value

number -= 5                      # Subtract and assign

print(number)


# -----------------------------------
# *= Operator
# -----------------------------------

number = 10                      # Store value

number *= 3                      # Multiply and assign

print(number)


# -----------------------------------
# /= Operator
# -----------------------------------

number = 20                      # Store value

number /= 4                      # Divide and assign

print(number)


# -----------------------------------
# //= Operator
# -----------------------------------

number = 20                      # Store value

number //= 3                     # Floor divide

print(number)


# -----------------------------------
# %= Operator
# -----------------------------------

number = 20                      # Store value

number %= 3                      # Find remainder

print(number)


# -----------------------------------
# **= Operator
# -----------------------------------

number = 5                       # Store value

number **= 2                     # Find power

print(number)
